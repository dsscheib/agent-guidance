def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prose(text):
    return INLINE_CODE.sub('', FENCE.sub('', text))


def rel(path, base=root):
    return path.relative_to(base).as_posix()


def package_git(*args):
    try:
        r = subprocess.run(['git', '-C', str(root), *args], capture_output=True, text=True)
    except OSError:
        return None
    return r.stdout if r.returncode == 0 else None


def git_ignored(base=root):
    try:
        r = subprocess.run(['git', '-C', str(base), 'ls-files', '--others', '--ignored', '--exclude-standard',
                            '--directory', '-z'], capture_output=True, text=True)
    except OSError:
        return set()
    return set(filter(None, r.stdout.split('\0'))) if r.returncode == 0 else set()


def walk(include_repo_only, manifest, base=root):
    repo_only = tuple(manifest.get('repo_only', []))
    ignored = git_ignored(base)
    found = []
    for dirpath, dirnames, filenames in os.walk(base):
        here = Path(dirpath)
        prefix = '' if here == base else rel(here, base) + '/'
        dirnames[:] = [d for d in dirnames if d not in SKIP_DIRS and prefix + d + '/' not in ignored
                       and not (here / d / '.git').exists()]
        found += [here / f for f in filenames if prefix + f not in ignored and (here / f).is_file()]
    for path in sorted(found):
        if not include_repo_only and rel(path, base).startswith(repo_only):
            continue
        yield path


def frontmatter(text):
    if not text.startswith('---\n') or '\n---\n' not in text[4:]:
        return {}
    fields = {}
    for line in text[4:text.index('\n---\n', 4)].splitlines():
        k, sep, v = line.partition(':')
        if sep:
            fields[k.strip()] = v.strip()
    return fields


def tool_paths(manifest):
    return {t: tuple(v['paths']) for t, v in manifest.get('tools', {}).items()}


def adopted_tools(manifest, record):
    meta = (record or {}).get('installed') or (record or {})
    return set(meta.get('tools') or manifest.get('tools', {}))


def for_tools(manifest, path, tools):
    matches = [(len(prefix), t) for t, prefixes in tool_paths(manifest).items() for prefix in prefixes if path.startswith(prefix)]
    if not matches:
        return True
    longest = max(n for n, _ in matches)
    return any(t in tools for n, t in matches if n == longest)


def in_modules(entry, modules):
    return entry.get('module', 'core') in modules and all(m in modules for m in entry.get('requires', []))


def yaml_quote(value):
    return json.dumps(value, ensure_ascii=False)


def role_body(source, fields, responsibilities):
    scope = ROLE_SCOPE.get(fields['kind'], 'Change only the files your task names, and coordinate anything else with the delegating agent.')
    packaged = source.startswith('docs/roles/')
    ref = 'docs/AGENT_TEAM.md' if packaged else 'MAINTAINING.md'
    return (f"You are the {fields['title']} on this {'project' if packaged else 'repository'}'s "
            f"{'specialist agent' if packaged else 'maintainer'} team.\n\n"
            'Before acting, read AGENTS.md at the repository root and follow it; it overrides this file. '
            f'Delegated work follows {ref}.\n\n'
            f'Responsibilities: {responsibilities}\n\n{scope}\n')


def render_agent(tool, source, fields, responsibilities):
    edits, runs = ROLE_KINDS[fields['kind']]
    name, description = fields['name'], fields['description']
    body = role_body(source, fields, responsibilities)
    marker = AGENT_MARKER + source + '. Edit that file, then regenerate.'
    if tool == 'codex':
        lines = [f'# {marker}', f'name = {yaml_quote(name)}', f'description = {yaml_quote(description)}']
        if fields.get('codex-model'):
            lines.append(f"model = {yaml_quote(fields['codex-model'])}")
        if fields.get('codex-effort'):
            lines.append(f"model_reasoning_effort = {yaml_quote(fields['codex-effort'])}")
        lines.append(f'developer_instructions = {yaml_quote(body)}')
        if not runs:
            lines += ['', '[features]', 'shell_tool = false']
        return '\n'.join(lines) + '\n'
    head = [f'name: {yaml_quote(name)}', f'description: {yaml_quote(description)}']
    if tool == 'claude':
        tools = ['Read', 'Grep', 'Glob'] + (['Edit', 'Write'] if edits else []) + (['Bash'] if runs else [])
        head += ([f"model: {fields['claude-model']}"] if fields.get('claude-model') else []) + [f"tools: {', '.join(tools)}"]
    elif tool == 'copilot':
        tools = ['read', 'search'] + (['edit'] if edits else []) + (['execute'] if runs else [])
        if fields.get('copilot-model'):
            head += [f"model: {fields['copilot-model']}", 'model-policy: required']
        head += [f'tools: {json.dumps(tools)}', 'strict-tools-list: true', 'include-custom-instructions: true']
    elif tool == 'antigravity':
        tools = ['view_file', 'grep_search'] + (['replace_file_content'] if edits else []) + (['run_command'] if runs else [])
        head += [f"model: {fields.get('antigravity-model') or 'inherit'}", 'mainAgent: false', 'subagent: true',
                 'commandExecutionPolicy: sandbox', 'tools:'] + [f'  - {t}' for t in tools]
    return '---\n' + '\n'.join(head) + f'\n---\n<!-- {marker} -->\n\n' + body


def roles(manifest, errors, directory=None, base=root):
    found = {}
    directory = directory or manifest.get('roles')
    if not directory or not (base / directory).is_dir():
        return found
    for source in sorted((base / directory).glob('*.md')):
        text = source.read_text()
        fields = frontmatter(text)
        missing = [f for f in ROLE_FIELDS if not fields.get(f)]
        if missing or not NAME.match(fields.get('name', '')) or fields.get('name') != source.stem:
            errors.append(f'{rel(source, base)}: role frontmatter needs {", ".join(ROLE_FIELDS)}, with name matching the filename')
            continue
        if fields['kind'] not in ROLE_KINDS:
            errors.append(f"{rel(source, base)}: role kind {fields['kind']!r} is not one of {', '.join(ROLE_KINDS)}")
            continue
        section = text.split('\n## Responsibilities\n', 1)
        responsibilities = ' '.join(section[1].split('\n## ', 1)[0].split()) if len(section) == 2 else ''
        if not responsibilities:
            errors.append(f'{rel(source, base)}: role needs a "## Responsibilities" section')
            continue
        found[fields['name']] = (rel(source, base), fields, responsibilities)
    return found


def expected_agents(manifest, errors, tools=None, directory=None, base=root):
    expected = {}
    for name, (source, fields, responsibilities) in roles(manifest, errors, directory, base).items():
        for target in manifest.get('agent_dirs', []):
            path = f"{target['dir']}/{name}{target['suffix']}"
            if tools is not None and not for_tools(manifest, path, tools):
                continue
            expected[path] = (render_agent(target['tool'], source, fields, responsibilities), name)
    return expected


def active_roles(manifest, template):
    team = manifest.get('maintainer_roles')
    return team if template and team and (root / team).is_dir() else manifest.get('roles')


def render_skill(source_rel, name, description):
    return (f'---\nname: {name}\ndescription: {json.dumps(description)}\n---\n'
            f'{SKILL_MARKER}{source_rel}. Edit that file, then regenerate. -->\n\n'
            f'# {name}\n\nRead `{source_rel}` from the repository root and follow it exactly. '
            'That file is the authoritative procedure; this wrapper only makes it discoverable as a skill.\n')


def expected_adapters(manifest, errors, tools=None, template=False, base=root, installed_files=None, include_maintainer_roles=None):
    expected = {}
    repo_only = tuple(manifest.get('repo_only', []))
    is_template_source = template or (base / 'MAINTAINING.md').is_file()
    if include_maintainer_roles is None:
        include_maintainer_roles = template
    source_dir = base / manifest['procedures']
    if source_dir.is_dir():
        for source in sorted(source_dir.glob('*.md')):
            srel = rel(source, base)
            if is_template_source and srel.startswith(repo_only):
                continue
            if not template and installed_files is not None and srel not in installed_files:
                continue
            fields = frontmatter(source.read_text())
            name, description = fields.get('name', ''), fields.get('description', '')
            if not template and (not name or not description):
                continue
            if not NAME.match(name) or name != source.stem or not description:
                errors.append(f'{srel}: frontmatter needs name matching the filename and a description')
                continue
            for adapter in manifest['adapters']:
                if tools is not None and not for_tools(manifest, adapter['dir'] + '/', tools):
                    continue
                expected[f"{adapter['dir']}/{name}/SKILL.md"] = render_skill(srel, name, description)
    if include_maintainer_roles:
        agents = expected_agents(manifest, errors, tools, active_roles(manifest, True), base)
        foreign = [p for p in agents if (base / p).is_file()
                   and not any(m in (base / p).read_text(errors='replace') for m in AGENT_MARKERS)]
        for path in foreign:
            errors.append(f'{path} exists but was not generated from its role; rename the role or move that file')
        expected.update({path: content for path, (content, _) in agents.items() if path not in foreign})
    return expected


def generated_agents(manifest, tools=None, template=False, base=root):
    found, roles_dir = set(), active_roles(manifest, template)
    if not roles_dir:
        return found
    for target in manifest.get('agent_dirs', []):
        d = base / target['dir']
        if not d.is_dir():
            continue
        for p in d.glob('*' + target['suffix']):
            path = rel(p, base)
            text = p.read_text(errors='replace')
            if (tools is None or for_tools(manifest, path, tools)) and any(f'{m}{roles_dir}/' in text for m in AGENT_MARKERS):
                found.add(path)
    return found


def existing_adapters(manifest, tools=None, template=False, base=root):
    found = set()
    for adapter in manifest['adapters']:
        if tools is not None and not for_tools(manifest, adapter['dir'] + '/', tools):
            continue
        d = base / adapter['dir']
        if d.is_dir():
            for p in d.glob('*/SKILL.md'):
                if template or SKILL_MARKER in p.read_text(errors='replace'):
                    found.add(rel(p, base))
    return found | generated_agents(manifest, tools, template, base)


