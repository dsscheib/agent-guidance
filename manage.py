def check_budget(errors, template=True):
    hint = 'move history to docs/RELEASE_NOTES.md or delete it'
    for path, limit in LINE_LIMITS.items():
        target = root / path
        if target.is_file():
            lines = len(target.read_text().splitlines())
            if lines > limit:
                errors.append(f'{path}: {lines} lines exceeds the {limit}-line budget; {hint}')
    profile = root / 'PROJECT_PROFILE.md'
    if profile.is_file():
        dated = [h for h in HEADING.findall(prose(profile.read_text())) if DATED.search(h)]
        if dated:
            errors.append(f'PROJECT_PROFILE.md: {len(dated)} dated heading(s), such as "{dated[0].strip()}"; '
                          f'this file holds stable facts only; {hint}')
    if template and (root / 'AGENTS.md').is_file():
        size = (root / 'AGENTS.md').stat().st_size
        if size > AGENTS_MAX_BYTES:
            errors.append(f'AGENTS.md: {size} bytes exceeds the {AGENTS_MAX_BYTES}-byte template ceiling')
    for path in POINTER_FILES:
        target = root / path
        if target.is_file():
            text = target.read_text()
            content = [line for line in text.splitlines() if line.strip()]
            if 'AGENTS.md' not in text or len(content) > POINTER_MAX_LINES:
                errors.append(f'{path}: tool instruction files may only point to AGENTS.md (at most {POINTER_MAX_LINES} lines)')


def placeholders(files, manifest):
    md = {rel(p) for p in files if p.suffix == '.md'} | {e['path'] for e in manifest['files'] if e['path'].endswith('.md')}
    counts = {}
    for rel_path in sorted(md):
        path = root / rel_path
        if not path.is_file():
            continue
        text = path.read_text()
        if rel_path == 'PROJECT_PROFILE.md':
            before, _, after = text.partition(STAGE_MARKER)
            code, release = len(PLACEHOLDER.findall(prose(before))), len(PLACEHOLDER.findall(prose(after)))
        else:
            code, release = 0, len(PLACEHOLDER.findall(prose(text)))
        if code or release:
            counts[rel_path] = (code, release)
    return counts


def run_template_checks(manifest, errors, require=None):
    files = list(walk(include_repo_only=True, manifest=manifest))
    exempt = tuple(manifest.get('shim_exempt', []))
    repo_only = () if (root / 'maintainer').is_dir() else tuple(manifest.get('repo_only', []))
    check_links([f for f in files if not rel(f).startswith(exempt)], errors, frozenset(), repo_only)
    check_shims(files, errors, exempt, True)
    check_adapters(manifest, errors, None, True)
    all_modules = set(manifest.get('modules', {}))
    agents = generate_agents(root / 'AGENTS.md', manifest, all_modules)
    if agents is not None and agents != (root / 'AGENTS.md').read_text():
        errors.append('AGENTS.md routing or procedure table does not match the manifest; run manage.py --sync')
    check_budget(errors, template=True)
    for path in GUARDRAIL_FILES:
        if (root / path).is_file():
            text = (root / path).read_text()
            for rule in manifest.get('guardrail_rules', []):
                if rule['module'] in all_modules and not has_guardrail(path, text, rule):
                    errors.append(f"{path} lacks the {rule['module']} guardrail that asks before you {rule['action']}")

    check_modules(manifest, errors)
    listed = {e['path']: e for e in manifest['files']}
    team = active_roles(manifest, True)
    maintainer_agents = set(expected_agents(manifest, [], None, team)) if team else set()
    for path, entry in listed.items():
        if not (root / path).is_file() or sha256(root / path) != entry.get('sha256'):
            errors.append(f'Missing or changed packaged file {path}; review, then run --update-manifest')
        if entry['kind'] == 'register' and (root / path).is_file() and DATED.search(prose((root / path).read_text())):
            errors.append(f'{path}: template registers must stay empty; move history to MAINTAINING.md')
    for path in walk(include_repo_only=False, manifest=manifest):
        if rel(path) not in listed and path != manifest_path and rel(path) not in maintainer_agents:
            errors.append(f'Unlisted file {rel(path)}; add it to the manifest or to repo_only')

    for label, cmd in (
        ('Install tests', [sys.executable, '-B', str(root / 'maintainer' / 'test_install.py')]),
        ('Scorer tests', [sys.executable, '-B', str(root / 'maintainer' / 'harness' / 'test_score.py')]),
        ('Scenario fixtures', [sys.executable, str(root / 'maintainer' / 'run_scenario.py'), '--check']),
    ):
        if Path(cmd[-2] if cmd[-1] == '--check' else cmd[-1]).is_file():
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode:
                errors.append(f'{label}:\n  ' + (r.stdout + r.stderr).strip().replace('\n', '\n  '))

    counts = placeholders(files, manifest)
    code_total = sum(c for c, _ in counts.values())
    release_total = sum(r for _, r in counts.values())
    if require == 'code' and code_total:
        errors.append(f'{code_total} placeholders remain above "## Command inventory" in PROJECT_PROFILE.md')
    if require == 'release' and code_total + release_total:
        errors.append(f'{code_total + release_total} placeholders remain; fill them or record exclusions before release')

    if errors:
        print('\n'.join(errors))
        print(f'FAIL (template mode): {len(errors)} problem(s).')
        sys.exit(1)
    print(f'PASS (template mode): {len(listed)} packaged files; links, adapters, shims and document budget consistent.')
    print(f'Placeholders: {code_total} before implementation, {release_total} before release. No project acceptance is implied.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--template', action='store_true', help='force template mode')
    mode.add_argument('--project', metavar='DIR', nargs='?', const='.', help='run scripts/verify.py on a project directory')
    parser.add_argument('--require', choices=['code', 'release'], help='fail if placeholders remain at this stage')
    parser.add_argument('--install', metavar='DIR', help='copy packaged files into a project directory')
    parser.add_argument('--force', action='store_true', help='with --install, overwrite existing files')
    parser.add_argument('--tier', choices=['prototype', 'internal', 'production', 'enterprise'],
                        help='with --install, install the core plus the modules this tier requires')
    parser.add_argument('--features', default='', help='with --install, comma-separated features: release-review, ui, ui-design, stack-go, stack-rust, embedded')
    parser.add_argument('--tools', default='', help='with --install, comma-separated tools: claude, codex, antigravity, copilot (default all)')
    parser.add_argument('--all', action='store_true', help='with --install, every module except enterprise & ui-design')
    parser.add_argument('--dry-run', action='store_true', help='with --install, list what would be copied and write nothing')
    parser.add_argument('--plan-upgrade', metavar='DIR', help='plan upgrading an installed project to this package; writes nothing there')
    parser.add_argument('--patch', metavar='FILE', help='with --plan-upgrade, write the proposed git-apply patch outside the project')
    parser.add_argument('--check-upgrade', metavar='DIR', help='check that open items, deployed revisions, and local changes survived an upgrade')
    parser.add_argument('--since', default='HEAD', help='with --check-upgrade, the pre-upgrade commit (default HEAD)')
    parser.add_argument('--sync', metavar='DIR', nargs='?', const='', help='regenerate AGENTS.md tables, skill wrappers, and (in template mode) maintainer agents')
    parser.add_argument('--sync-adapters', action='store_true', help='alias for --sync in the template repository')
    parser.add_argument('--update-manifest', action='store_true', help='refresh PACKAGE_MANIFEST.json hashes (template mode)')
    args = parser.parse_args()

    if args.project:
        proj = Path(args.project).resolve()
        verifier = proj / 'scripts' / 'verify.py'
        if not verifier.is_file():
            sys.exit(f'{proj} has no scripts/verify.py')
        cmd = [sys.executable, str(verifier)] + (['--require', args.require] if args.require else [])
        sys.exit(subprocess.run(cmd).returncode)

    manifest = json.loads(manifest_path.read_text())
    template = args.template or (root / 'MAINTAINING.md').exists()
    errors = []

    if args.plan_upgrade:
        plan_upgrade(manifest, args.plan_upgrade, args.patch)
        return
    if args.check_upgrade:
        check_upgrade(manifest, args.check_upgrade, args.since)
        return
    if args.install:
        if args.all and args.tier:
            parser.error('--all replaces --tier; give one or the other')
        install(manifest, args.install, args.force, args.tier, [f for f in args.features.split(',') if f], args.all, args.dry_run,
                [t for t in args.tools.split(',') if t])
        return
    if args.sync is not None or args.sync_adapters:
        if args.sync_adapters or args.sync == '':
            sync_target = None
        else:
            resolved = Path(args.sync).resolve()
            sync_target = None if resolved == root else str(resolved)
        sync_adapters(manifest, errors, sync_target, template=template and sync_target is None)
        if sync_target is not None:
            if errors:
                print('\n'.join(errors))
                sys.exit(1)
            return
    if args.update_manifest:
        if not template:
            sys.exit('--update-manifest is for the template repository.')
        update_manifest(manifest, errors)
    if not template:
        sys.exit('Run manage.py from the agent-guidance template repository (use scripts/verify.py inside installed projects).')
    run_template_checks(manifest, errors, args.require)


if __name__ == '__main__':
    main()
