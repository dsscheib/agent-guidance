def render_block(manifest, name, modules):
    tables = manifest.get('agents_tables', {})
    rows = [r['row'] for r in tables.get(name, []) if r['module'] in modules]
    notes = [r['row'] for r in tables.get(name + '_notes', []) if r['module'] in modules]
    is_v4 = str(manifest.get('version', '')).startswith('4.')
    if name == 'procedures':
        if not is_v4:
            text = '| Procedure | Use when |\n|---|---|\n' + ''.join(r + '\n' for r in rows)
        elif not rows and not notes:
            return ''
        else:
            text = '## On-demand skills\n\n| Skill | Use when |\n|---|---|\n' + ''.join(r + '\n' for r in rows)
    else:
        text = '| When the change touches… | Read before | Update after |\n|---|---|---|\n' + ''.join(r + '\n' for r in rows)
    if notes:
        text += '\n' + ' '.join(notes) + '\n'
    return text


def generate_agents(path, manifest, modules):
    if not path.is_file():
        return None
    return GENERATED.sub(lambda m: m.group(1) + render_block(manifest, m.group(2), modules) + m.group(4), path.read_text())


def strip_module_blocks(text, modules):
    def repl(m):
        if m.group(1) not in modules:
            return ''
        return ('\n' if m.group(0).startswith('\n') else '') + m.group(2)
    return MODULE_BLOCK.sub(repl, text)


def codex_rule(words):
    return re.compile(r'prefix_rule\(\n    pattern = \[' + re.escape(', '.join(f'"{w}"' for w in words))
                      + r'\],\n(?:    [^\n]*\n)*\)\n\n?')


def copilot_rule(words):
    return re.compile(r'^    \(' + re.escape(repr(words)) + r', [^\n]*\),\n', re.M)


def has_guardrail(path, text, rule):
    tool = GUARDRAIL_FILES[path]
    if tool == 'claude':
        return rule['claude'] in json.loads(text).get('permissions', {}).get('ask', [])
    return bool((codex_rule if tool == 'codex' else copilot_rule)(rule[tool]).search(text))


def without_guardrail(path, text, rule):
    tool = GUARDRAIL_FILES[path]
    if tool == 'claude':
        data = json.loads(text)
        ask = data.get('permissions', {}).get('ask', [])
        if rule['claude'] in ask:
            ask.remove(rule['claude'])
        return json.dumps(data, indent=2) + '\n'
    text = (codex_rule if tool == 'codex' else copilot_rule)(rule[tool]).sub('', text)
    return text.rstrip('\n') + '\n'


def effective(path, text, manifest, modules):
    if text is None:
        return None
    if path in GUARDRAIL_FILES:
        for rule in manifest.get('guardrail_rules', []):
            if rule['module'] not in modules:
                text = without_guardrail(path, text, rule)
        return text
    if path == 'AGENTS.md':
        return GENERATED.sub(lambda m: m.group(1) + render_block(manifest, m.group(2), modules) + m.group(4), text)
    if path == 'PROJECT_PROFILE.md' and str(manifest.get('version', '')).startswith('4.'):
        return strip_module_blocks(text, modules)
    return text


def expected_agents_blocks(manifest, modules):
    return {name: render_block(manifest, name, set(modules)) for name in ('routing', 'procedures')}


def expected_guardrail_checks(manifest, modules, tools):
    checks = []
    for rule in manifest.get('guardrail_rules', []):
        if rule['module'] not in modules:
            continue
        if 'claude' in tools:
            checks.append({'action': rule['action'], 'path': '.claude/settings.json', 'token': rule['claude']})
        if 'codex' in tools:
            checks.append({'action': rule['action'], 'path': '.codex/rules/guidance.rules',
                           'token': 'pattern = [' + ', '.join(f'"{w}"' for w in rule['codex']) + ']'})
        if 'copilot' in tools:
            checks.append({'action': rule['action'], 'path': '.github/hooks/guidance_guardrail.py',
                           'token': f"({rule['copilot']!r},"})
    return checks


def sync_adapters(manifest, errors, target_dir=None, template=True):
    base = Path(target_dir).resolve() if target_dir else root
    record = {}
    if not template or base != root:
        template = False
        for name in (GUIDANCE_FILE, LEGACY_MANIFEST):
            if (base / name).is_file():
                record = json.loads((base / name).read_text())
                break
    meta = record.get('installed') or record
    modules = set(manifest.get('modules', {})) if template else set(meta.get('modules') or manifest.get('modules', {}))
    tools = None if template else (set(meta['tools']) if meta.get('tools') else None)
    installed_files = None
    if not template and record.get('files'):
        installed_files = {e['path'] if isinstance(e, dict) else e for e in record['files']}

    agents = generate_agents(base / 'AGENTS.md', manifest, modules)
    if agents is not None and agents != (base / 'AGENTS.md').read_text():
        (base / 'AGENTS.md').write_text(agents)
        print('Regenerated the AGENTS.md routing and procedure tables')
    if not template and (base / GUIDANCE_FILE).is_file() and 'agents_blocks' in record:
        blocks = expected_agents_blocks(manifest, modules)
        if record.get('agents_blocks') != blocks:
            record['agents_blocks'] = blocks
            (base / GUIDANCE_FILE).write_text(json.dumps(record, indent=2) + '\n')

    expected = expected_adapters(manifest, errors, tools, template, base, installed_files)
    for path in existing_adapters(manifest, tools, template, base) - expected.keys():
        (base / path).unlink()
        print('Removed orphaned adapter: ' + path)
    for path, content in expected.items():
        target = base / path
        if not target.is_file() or target.read_text() != content:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
            print('Wrote adapter: ' + path)


def update_manifest(manifest, errors):
    expected = expected_adapters(manifest, errors, template=True, include_maintainer_roles=False)
    entries = [e for e in manifest['files'] if e['kind'] != 'adapter' or e['path'] in expected]
    listed = {e['path'] for e in entries}
    entries += [{'path': p, 'kind': 'adapter'} for p in sorted(expected.keys() - listed)]
    by_path = {e['path']: e for e in entries}
    for entry in entries:
        if entry['kind'] == 'adapter' and entry['path'].endswith('/SKILL.md'):
            name = entry['path'].split('/')[-2]
            proc = by_path.get(f"{manifest['procedures']}/{name}.md", {})
            entry['module'] = proc.get('module', 'core')
            if proc.get('requires'):
                entry['requires'] = proc['requires']
            else:
                entry.pop('requires', None)
    for entry in entries:
        path = root / entry['path']
        if path.is_file():
            entry['bytes'], entry['sha256'] = path.stat().st_size, sha256(path)
        else:
            errors.append('Manifest entry has no file: ' + entry['path'])
    manifest['files'] = entries
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Updated manifest: {len(entries)} entries.')


def source_identity():
    commit = package_git('rev-parse', 'HEAD')
    status = package_git('status', '--porcelain')
    remote = package_git('config', '--get', 'remote.origin.url')
    return {
        'repository': remote.strip() if remote else 'unknown',
        'commit': commit.strip() if commit else 'unknown',
        'dirty': None if status is None else bool(status.strip()),
        'date': date.today().isoformat(),
    }


def v2_modules(modules):
    return {m for m in modules if m not in NOT_IN_V2}


def resolve_modules(manifest, tier, features, everything=False):
    unknown = [f for f in features if f not in manifest['features']]
    if unknown:
        sys.exit(f"Unknown feature(s): {', '.join(unknown)}; choose from {', '.join(manifest['features'])}")
    modules = v2_modules(manifest['modules']) if everything else set(manifest['tiers'][tier]) if tier else set()
    for feature in features:
        modules.update(manifest['features'][feature])
    return sorted(modules)


def tier_choice(manifest, target):
    lines, previous = ['Choose a tier; nothing was installed.'], set()
    for tier, mods in manifest['tiers'].items():
        added = [m for m in mods if m not in previous] if previous else mods
        lines.append(f"  {tier:<11} {'+ ' if previous else ''}{', '.join(added)}: {TIER_AUDIENCE.get(tier, '')}")
        previous = set(mods)
    lines += [
        f"Features: {', '.join(manifest['features'])}",
        f'Example: --install {target} --tier internal --features release-review',
        'Preview first with --dry-run. The 2.x set (every module except enterprise & ui-design): --all',
    ]
    return '\n'.join(lines)


def add_profile_rows(profile, manifest, modules):
    if not profile.is_file():
        return []
    text = profile.read_text()
    purpose = lambda row: row.strip().strip('|').split('|')[0].strip()
    present = {purpose(l) for l in text.splitlines() if l.lstrip().startswith('|')}
    new = [r['row'] for r in manifest.get('profile_rows', []) if r['module'] in modules and purpose(r['row']) not in present]
    if not new:
        return []
    anchor = next((l for l in text.splitlines() if l.startswith('| Guidance integrity |')), None)
    if anchor is None:
        return []
    profile.write_text(text.replace(anchor, '\n'.join(new) + '\n' + anchor, 1))
    return [purpose(r) for r in new]


def add_release_profile_section(profile, modules):
    if 'release' not in modules or not profile.is_file():
        return
    text = profile.read_text()
    if '## Release qualification profile' in text:
        return
    m = MODULE_BLOCK.search((root / 'PROJECT_PROFILE.md').read_text())
    if m and m.group(1) == 'release':
        profile.write_text(text.rstrip('\n') + '\n' + m.group(2) + '\n')


def build_guidance_record(manifest, tier, features, modules, tools, source, wanted_entries):
    required = set(manifest['tiers'].get(tier or '', [])) | {
        m for f in features for m in manifest['features'].get(f, [])}
    module_files = {
        m: [e['path'] for e in manifest['files'] if e.get('module') == m and for_tools(manifest, e['path'], tools)]
        for m in sorted(required)
    }
    wanted_paths = {e['path'] for e in wanted_entries}
    file_entries = []
    for e in wanted_entries:
        eff = effective(e['path'], packaged_text(manifest, e['path']), manifest, set(modules))
        sha = hashlib.sha256(eff.encode()).hexdigest() if eff is not None else e.get('sha256')
        file_entries.append({'path': e['path'], 'kind': e.get('kind', ''), 'sha256': sha})
    return {
        'version': manifest['version'],
        'installed_from': source,
        'installed': {
            'tier': tier,
            'features': list(features),
            'modules': modules,
            'tools': tools,
        },
        'module_files': module_files,
        'agents_blocks': expected_agents_blocks(manifest, modules),
        'guardrail_checks': expected_guardrail_checks(manifest, modules, tools),
        'files': file_entries,
        'uninstalled': [e['path'] for e in manifest['files'] if e['path'] not in wanted_paths],
    }


