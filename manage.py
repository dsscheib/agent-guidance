def install(manifest, target, force, tier=None, features=(), everything=False, dry_run=False, tools=()):
    target = Path(target).resolve()
    if not target.is_dir() or target == root:
        sys.exit(f'Install target must be an existing directory other than this package: {target}')
    prev_doc, previous, prev_legacy = read_previous_install(target)
    prev_modules = set(previous.get('modules', []))
    if prev_legacy:
        prev_modules = {m for old in prev_modules for m in V3_MODULE_MAP.get(old, ())} & set(manifest['modules'])
    if not (tier or everything or prev_modules):
        sys.exit(tier_choice(manifest, target))
    modules = sorted(set(resolve_modules(manifest, tier, list(features), everything)) | prev_modules)
    all_features = sorted((set(features) | {f for f in previous.get('features', []) if f in manifest['features']}))
    unknown = [t for t in tools if t not in manifest.get('tools', {})]
    if unknown:
        sys.exit(f"Unknown tool(s): {', '.join(unknown)}; choose from {', '.join(manifest.get('tools', {}))}")
    chosen = sorted(set(tools) | set(previous.get('tools', []))) if tools or previous.get('tools') else sorted(manifest.get('tools', {}))
    wanted_entries = [e for e in manifest['files'] if in_modules(e, modules) and for_tools(manifest, e['path'], chosen)]
    wanted = [e['path'] for e in wanted_entries]
    chosen_tier = tier or previous.get('tier')
    if dry_run:
        new = [p for p in wanted + [GUIDANCE_FILE] if force or not (target / p).exists()]
        print(f"Would install modules: {', '.join(modules)}" + (f' (tier {chosen_tier})' if chosen_tier else '')
              + f"; tools: {', '.join(chosen)}")
        print(f'Would copy {len(new)} files into {target}' + (':\n  ' + '\n  '.join(new) if new else '.'))
        kept = len(wanted) + 1 - len(new)
        if kept:
            print(f'Would skip {kept} existing files.')
        print('Nothing was written (--dry-run).')
        return

    copied, skipped = [], []
    for path in wanted:
        dest = target / path
        if dest.exists() and not force:
            if path in GUARDRAIL_FILES and prev_modules:
                package_text = (root / path).read_text()
                if dest.read_text() == effective(path, package_text, manifest, prev_modules):
                    new_text = effective(path, package_text, manifest, set(modules))
                    if new_text != dest.read_text():
                        dest.write_text(new_text)
                        copied.append(path)
                        continue
            skipped.append(path)
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        eff = effective(path, packaged_text(manifest, path), manifest, set(modules))
        if eff != packaged_text(manifest, path):
            dest.write_text(eff)
        else:
            shutil.copy2(root / path, dest)
        copied.append(path)

    if not (target / 'README.md').exists():
        (target / 'README.md').write_text(f'# {target.name}\n\nProject overview and usage.\n')
        copied.append('README.md')

    record_dest = target / GUIDANCE_FILE
    source = prev_doc.get('installed_from') if (record_dest.exists() and not force) else source_identity()
    record = build_guidance_record(manifest, chosen_tier, all_features, modules, chosen, source or source_identity(), wanted_entries)
    if not record_dest.exists() or force or chosen_tier != previous.get('tier') or modules != sorted(prev_modules) or chosen != sorted(previous.get('tools', [])):
        record_dest.write_text(json.dumps(record, indent=2) + '\n')
        copied.append(GUIDANCE_FILE)
    else:
        skipped.append(GUIDANCE_FILE)

    agents = generate_agents(target / 'AGENTS.md', manifest, set(modules))
    if agents is not None and agents != (target / 'AGENTS.md').read_text():
        (target / 'AGENTS.md').write_text(agents)
    add_release_profile_section(target / 'PROJECT_PROFILE.md', set(modules))
    added = add_profile_rows(target / 'PROJECT_PROFILE.md', manifest, set(modules))
    if added:
        print('Added command-inventory rows: ' + ', '.join(added))
    print(f"Installed modules: {', '.join(modules)}" + (f" (tier {chosen_tier})" if chosen_tier else '')
          + f"; tools: {', '.join(manifest['tools'][t]['name'] for t in chosen)}")
    print(f'Copied {len(copied)} files into {target}.')
    if skipped:
        print('Skipped existing files (merge by hand or rerun with --force):\n  ' + '\n  '.join(skipped))
    print('Next: fill PROJECT_PROFILE.md above "## Command inventory", then run: python3 scripts/verify.py --require code')


def unified(path, old, new):
    def lines(text):
        out = (text or '').splitlines(keepends=True)
        if out and not out[-1].endswith('\n'):
            out[-1] += '\n\\ No newline at end of file\n'
        return out
    head = [f'diff --git a/{path} b/{path}\n']
    head += ['new file mode 100644\n'] if old is None else ['deleted file mode 100644\n'] if new is None else []
    body = list(difflib.unified_diff(lines(old), lines(new), '/dev/null' if old is None else 'a/' + path,
                                     '/dev/null' if new is None else 'b/' + path))
    return ''.join(head + body) if body else ''


def load_old_manifest(commit, local_record, is_v3, fallback):
    if is_v3:
        return local_record
    if commit:
        raw = package_git('show', f'{commit}:PACKAGE_MANIFEST.json')
        if raw:
            return json.loads(raw)
    return fallback


def project_record(target, manifest):
    g = target / GUIDANCE_FILE
    if g.is_file():
        record = json.loads(g.read_text())
        modules = set(record.get('installed', {}).get('modules') or v2_modules(manifest['modules']))
        return record, modules, record.get('installed_from', {}).get('commit'), False, g.read_text()
    legacy = target / LEGACY_MANIFEST
    if legacy.is_file():
        record = json.loads(legacy.read_text())
        modules = set(record.get('installed', {}).get('modules') or v2_modules(record.get('modules') or manifest['modules']))
        return record, modules, record.get('installed_from', {}).get('commit'), True, legacy.read_text()
    sys.exit(f'{target} has neither {GUIDANCE_FILE} nor {LEGACY_MANIFEST}, so it is not a package-layout install. '
             'Follow docs/procedures/upgrade-guidance.md by hand.')


def plan_upgrade(manifest, target, patch=None):
    target = Path(target).resolve()
    if not target.is_dir() or target == root:
        sys.exit(f'Upgrade target must be an existing directory other than this package: {target}')
    if patch and Path(patch).resolve().is_relative_to(target):
        sys.exit('Write the patch outside the project, so planning changes nothing in it.')
    record, raw_modules, base_commit, is_v3, old_record_text = project_record(target, manifest)
    if is_v3:
        modules = {m for old_m in raw_modules for m in V3_MODULE_MAP.get(old_m, ())} & set(manifest['modules'])
    else:
        modules = raw_modules & set(manifest['modules'])
    old_manifest = load_old_manifest(base_commit, record, is_v3, manifest)
    baseline = {e['path']: e for e in record.get('files', [])}
    tools = adopted_tools(manifest, record)
    wanted_entries = [e for e in manifest['files'] if in_modules(e, modules) and for_tools(manifest, e['path'], tools)]
    wanted = {e['path']: e for e in wanted_entries}
    have_base = bool(base_commit and package_git('cat-file', '-e', f'{base_commit}^{{commit}}') is not None)
    source = source_identity()
    rows, diffs, blocked = [], [], []

    def base_text(path):
        text = package_git('show', f'{base_commit}:{path}') if have_base else None
        return effective(path, text, old_manifest, raw_modules)

    for path in sorted(baseline.keys() | wanted.keys()):
        entry = wanted.get(path) or baseline[path]
        kind = entry.get('kind', '')
        file = target / path
        mine = file.read_text() if file.is_file() else None
        new = effective(path, packaged_text(manifest, path), manifest, modules) if path in wanted else None
        old = base_text(path) if path in baseline else None
        if old is None and path in baseline and mine is not None:
            same_base = sha256(file) == baseline[path].get('sha256')
            old = mine if same_base else None
        upstream = (new != old or old is None) if path in baseline else True
        modified = mine != old if path in baseline and old is not None else None
        if mine == new:
            if new is not None:
                rows.append(('keep', path, kind, ''))
            continue
        elif not upstream:
            continue
        elif mine is None:
            if path in baseline and new is None:
                continue
            action, note = ('add', '') if path not in baseline else ('absent', 'removed here; upstream changed it')
        elif path not in baseline:
            action, note = 'conflict', 'the project has its own file at this path'
        elif new is None:
            if path == 'README.md':
                if modified is False:
                    new = f'# {target.name}\n\nProject overview and usage.\n'
                    action, note = 'replace', 'replaced old guidance README with project stub'
                else:
                    action, note = 'review', 'project README (no longer managed upstream); check for links to retired docs'
            else:
                action, note = ('remove', 'removed upstream') if modified is False else ('review', 'removed upstream; modified here')
        elif modified is False:
            action, note = 'replace', ''
        elif modified is None:
            action, note = 'review', f'no baseline text for commit {base_commit or "unrecorded"}; merge by hand'
        elif kind in FILLED_KINDS and path != 'AGENTS.md':
            action, note = 'review', f'{kind} filled in here; carry structural changes by hand'
        else:
            with tempfile.TemporaryDirectory() as tmp:
                names = []
                for name, text in (('mine', mine), ('base', old), ('new', new)):
                    (Path(tmp) / name).write_text(text)
                    names.append(str(Path(tmp) / name))
                merged = subprocess.run(['git', 'merge-file', '-p', '-L', 'project', '-L', 'installed', '-L', 'upstream', *names],
                                        capture_output=True, text=True)
            if merged.returncode == 0:
                action, note = 'merge', 'project changes kept'
                diffs.append(unified(path, mine, merged.stdout))
            else:
                hunks = merged.returncode if merged.returncode > 0 else '?'
                action, note = 'conflict', f'{hunks} conflicting hunk(s) with local changes'
        if action in ('replace', 'add', 'remove'):
            diffs.append(unified(path, mine, new))
        if action in ('replace', 'add', 'remove', 'merge'):
            parent = next(p for p in [file, *file.parents] if p.exists())
            if not os.access(parent if parent.is_dir() else parent.parent, os.W_OK):
                blocked.append(path)
        rows.append((action, path, kind, note))

    installed = record.get('installed') or {'tier': None, 'features': []}
    features = [f for f in (installed.get('features') or []) if f in manifest['features']]
    proposed = build_guidance_record(manifest, installed.get('tier'), features, sorted(modules), sorted(tools), source, wanted_entries)
    proposed_text = json.dumps(proposed, indent=2) + '\n'
    if is_v3:
        rows.append(('remove', LEGACY_MANIFEST, 'manifest', f'replaced by {GUIDANCE_FILE}'))
        rows.append(('add', GUIDANCE_FILE, 'manifest', ''))
        diffs.append(unified(LEGACY_MANIFEST, old_record_text, None))
        diffs.append(unified(GUIDANCE_FILE, None, proposed_text))
    else:
        diffs.append(unified(GUIDANCE_FILE, old_record_text, proposed_text))

    print(f"Upgrade plan for {target}: installed from {(base_commit or 'an unrecorded commit')[:12]}, "
          f"package at {source['commit'][:12]}{' (dirty checkout)' if source['dirty'] else ''}. Nothing was written to the project.")
    if not have_base:
        print('  The installed commit is not in this checkout, so local changes cannot be merged automatically.')
    labels = {
        'replace': 'Replace (unmodified here)',
        'add': 'Add (new upstream)',
        'merge': 'Merge (both changed; merges cleanly)',
        'conflict': 'Conflict (merge by hand)',
        'review': 'Review (by hand)',
        'remove': 'Remove (removed upstream)',
        'keep': 'Already current',
        'absent': 'Absent here (record the exclusion or restore it)',
    }
    for action in PLAN_ORDER:
        group = [r for r in rows if r[0] == action]
        if group:
            print(f'{labels[action]}: {len(group)}')
            for _, path, kind, note in (group if action != 'keep' else ()):
                print(f'  {path}' + (f' ({note})' if note else ''))
    if any(r[0] in ('conflict', 'review') for r in rows) and have_base:
        print(f"Upstream change for a file: git -C {root} diff {base_commit[:12]} {source['commit'][:12]} -- PATH")
    if any(r[1].startswith(('.agents/', '.claude/', '.codex/')) or r[2] == 'procedure' for r in rows if r[0] != 'keep'):
        print(f'After merging procedures, regenerate the skill copies: python3 {root / "manage.py"} --sync {target}')
    if blocked:
        print('Not writable here (ask the user to apply these): ' + ', '.join(blocked))
    if patch:
        Path(patch).write_text(''.join(d for d in diffs if d))
        print(f'Proposed patch (replace, add, merge and remove, plus {GUIDANCE_FILE}): {Path(patch).resolve()}')
    since_commit = subprocess.run(['git', '-C', str(target), 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip()
    print('This is a plan only. Show it to the user with your questions about each conflict and review item, then stop. '
          'Apply nothing, including the replace and add changes, until the user approves. After applying, run this '
          f"checkout's checker: python3 {root / 'manage.py'} --check-upgrade {target} "
          f"--since {since_commit or '<commit before the upgrade>'}")


def agent_from_role(manifest, path, role_text):
    for target in manifest.get('agent_dirs', []):
        prefix, suffix = target['dir'] + '/', target['suffix']
        if not (path.startswith(prefix) and path.endswith(suffix)) or role_text is None:
            continue
        name, fields = path[len(prefix):-len(suffix)], frontmatter(role_text)
        section = role_text.split('\n## Responsibilities\n', 1)
        responsibilities = ' '.join(section[1].split('\n## ', 1)[0].split()) if len(section) == 2 else ''
        if fields.get('name') != name or fields.get('kind') not in ROLE_KINDS or not responsibilities:
            return None
        source = f"{manifest.get('roles') or 'docs/roles'}/{name}.md"
        return render_agent(target['tool'], source, fields, responsibilities)
    return None


def check_upgrade(manifest, target, since='HEAD'):
    target = Path(target).resolve()

    def git(*args):
        r = subprocess.run(['git', '-C', str(target), *args], capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"git {' '.join(args)} failed in {target}: {r.stderr.strip()}")
        return r.stdout

    before_files = [p for p in git('ls-tree', '-r', '--name-only', since).splitlines()]
    shown = lambda p: subprocess.run(['git', '-C', str(target), 'show', f'{since}:{p}'], capture_output=True, text=True).stdout
    now_files = [p for p in git('ls-files', '--cached', '--others', '--exclude-standard').splitlines() if (target / p).is_file()]
    now_docs = '\n'.join((target / p).read_text(errors='replace') for p in now_files if p.endswith('.md'))
    problems = []
    open_before, revisions = set(), set()
    for path in (p for p in before_files if p.endswith('.md')):
        text = shown(path)
        open_before |= {m.group(1) for m in OPEN_ITEM.finditer(text) if re.search(r'(?i)\|\s*open\b', '|' + m.group(2))}
        revisions |= {r for line in text.splitlines() if re.search(r'(?i)deploy', line) for r in REVISION.findall(line)}
    still_open = {m.group(1) for m in OPEN_ITEM.finditer(now_docs) if re.search(r'(?i)\|\s*open\b', '|' + m.group(2))}
    lost = sorted(i for i in open_before if not re.search(rf'\b{re.escape(i)}\b', now_docs))
    closed = sorted(i for i in open_before - still_open if i not in lost)
    if lost:
        problems.append('Open items no longer in any document: ' + ', '.join(lost))
    if closed:
        problems.append('Open items no longer marked open (an upgrade does not close them): ' + ', '.join(closed))
    missing = sorted(r for r in revisions if r not in now_docs)
    if missing:
        problems.append('Deployed revisions no longer in any document: ' + ', '.join(missing))

    deleted = sorted(set(before_files) - set(now_files))
    code = [p for p in now_files if not p.endswith(('.md', '.json'))]
    for gone in deleted:
        if gone.endswith('/SKILL.md'):
            continue
        name = Path(gone).name
        users = [p for p in code if name in (target / p).read_text(errors='replace') and gone not in LEGACY_REFERENCES.get(p, ())]
        if users:
            problems.append(f'{gone} was deleted but {", ".join(users)} still names it')

    raw_g, raw_l = shown(GUIDANCE_FILE), shown(LEGACY_MANIFEST)
    record = json.loads(raw_g or raw_l or '{}')
    is_v3 = not raw_g and bool(raw_l)
    commit = record.get('installed_from', {}).get('commit')
    modules = set(record.get('installed', {}).get('modules') or v2_modules(record.get('modules') or manifest['modules']))
    packaged = [e['path'] for e in record.get('files', []) if e['path'] in before_files
                and (e.get('kind') not in FILLED_KINDS or e['path'] == 'AGENTS.md')]
    flat = lambda text: ' '.join(text.split())
    hashes = {e['path']: e.get('sha256') for e in record.get('files', [])}
    unchecked = []
    have_commit = bool(commit and package_git('cat-file', '-e', f'{commit}^{{commit}}') is not None)
    old_manifest = load_old_manifest(commit, record, is_v3, manifest)
    roles_dir = old_manifest.get('roles') or 'docs/roles'

    for path in packaged:
        mine_before = shown(path)
        if (target / path).is_file() and (target / path).read_text() == mine_before:
            continue
        text = package_git('show', f'{commit}:{path}') if have_commit else None
        if text is None and have_commit:
            name = Path(path).name.split('.')[0]
            text = agent_from_role(old_manifest, path, package_git('show', f'{commit}:{roles_dir}/{name}.md'))
        base = effective(path, text, old_manifest, modules)
        if base is None:
            if hashlib.sha256(mine_before.encode()).hexdigest() != hashes.get(path):
                unchecked.append(path)
            continue
        if mine_before == base:
            continue
        now = flat((target / path).read_text()) if (target / path).is_file() else flat(now_docs)
        base_lines = base.splitlines()
        dropped = []
        for line in set(mine_before.splitlines()) - set(base_lines):
            close = difflib.get_close_matches(line, base_lines, n=1, cutoff=0.6)
            words, old_words = line.split(), (close[0].split() if close else [])
            runs = [' '.join(words[j1:j2]) for op, _, _, j1, j2 in difflib.SequenceMatcher(None, old_words, words).get_opcodes()
                    if op in ('insert', 'replace')]
            runs = [r.strip('-*|# ') for r in runs if len(r.strip('-*|# ')) > 3]
            if any(flat(r) not in now for r in runs):
                dropped.append(line)
        if dropped:
            problems.append(f'{path}: {len(dropped)} local change(s) not found verbatim, first: {dropped[0].strip()[:80]}')
    if unchecked and not have_commit:
        problems.append(f"Could not check local changes in {', '.join(unchecked)}: the installed commit "
                        f"{(commit or 'unrecorded')[:12]} is not in this checkout. Run from the guidance checkout: "
                        f"python3 {root / 'manage.py'} --check-upgrade {target} --since {since}")
    elif unchecked:
        problems.append(f"Could not check local changes in {', '.join(unchecked)}: the installed commit "
                        f"{commit[:12]} holds no installed text for them. Compare them with {since} by hand.")
    for path in now_files:
        if path.endswith('.md') and re.search(r'(?m)^(<{7} |>{7} )', (target / path).read_text(errors='replace')):
            problems.append(f'{path}: unresolved merge conflict markers')
    if problems:
        print('\n'.join(problems))
    print(f"Upgrade check against {since}: {len(open_before)} open items, {len(revisions)} deployed revisions, "
          f"{len(deleted)} deleted files, {len(packaged)} packaged files checked; "
          + (f'{len(problems)} problem(s).' if problems else 'nothing lost.'))
    if problems:
        sys.exit(1)


def check_links(files, errors, uninstalled=frozenset(), repo_only=(), base=root):
    skipped = 0
    for path in files:
        if path.suffix != '.md':
            continue
        for link in LINK.findall(prose(path.read_text(errors='replace'))):
            if '://' in link or link.startswith(('#', 'mailto:')):
                continue
            target = (path.parent / link.split('#')[0]).resolve()
            if target.is_relative_to(base) and not target.exists() and rel(target, base).startswith(repo_only):
                continue
            if target.is_relative_to(base) and not target.exists() and rel(target, base) in uninstalled:
                skipped += 1
            elif not target.is_relative_to(base) or not target.exists():
                errors.append(f'{rel(path, base)}: unresolved or escaping link {link}')
    return skipped


def check_shims(files, errors, exempt, claude=True, base=root):
    for path in files:
        if not claude:
            break
        if path.name == 'AGENTS.md' and not rel(path, base).startswith(exempt):
            shim = path.with_name('CLAUDE.md')
            if not shim.is_file() or '@AGENTS.md' not in shim.read_text(errors='replace'):
                errors.append(f'{rel(path, base)}: needs a sibling CLAUDE.md containing @AGENTS.md for Claude Code')


def check_modules(manifest, errors):
    known = set(manifest.get('modules', {}))
    modules_of = {e['path']: e.get('module') for e in manifest['files']}
    for path, module in modules_of.items():
        if module not in known:
            errors.append(f'{path}: manifest module {module!r} is not defined under "modules"')
    for group in ('tiers', 'features'):
        for name, mods in manifest.get(group, {}).items():
            for m in mods:
                if m not in known:
                    errors.append(f'{group} {name!r} names unknown module {m!r}')
    requires_of = {e['path']: e.get('requires', []) for e in manifest['files']}
    for path, required in requires_of.items():
        for m in required:
            if m not in known:
                errors.append(f'{path}: requires unknown module {m!r}')
    for path, module in modules_of.items():
        if path.endswith('/SKILL.md'):
            procedure = f"{manifest['procedures']}/{path.split('/')[-2]}.md"
            if modules_of.get(procedure) != module:
                errors.append(f'{path}: adapter module {module!r} differs from its procedure {procedure} ({modules_of.get(procedure)!r})')


