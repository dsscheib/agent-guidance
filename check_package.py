#!/usr/bin/env python3
"""Install, integrity, link, adapter, placeholder and document-budget checks for the reusable guidance package.

Template mode (MAINTAINING.md present) checks the package itself; project mode checks an installed copy.
Only --install, --sync-adapters and --update-manifest write files; --plan-upgrade and --check-upgrade only read the project. --verify runs the project's gate commands.
"""
from datetime import date
from pathlib import Path
import argparse, difflib, hashlib, json, os, re, shutil, subprocess, sys, tempfile, time

root = Path(__file__).resolve().parent
manifest_path = root / 'PACKAGE_MANIFEST.json'
STAGE_MARKER = '<!-- stage: release -->'
SKIP_DIRS = {'.git', '__pycache__', 'node_modules', 'target'}  # dependency and build trees are not the project's documents
PLACEHOLDER = re.compile(r'\{\{[^}]+\}\}')
LINK = re.compile(r'\]\(([^)\s]+)(?:\s+"[^"]*")?\)')
FENCE = re.compile(r'^(```|~~~).*?^\1[ \t]*$', re.M | re.S)
INLINE_CODE = re.compile(r'`[^`\n]*`')
DATED = re.compile(r'\b20\d\d-\d\d-\d\d\b')
NAME = re.compile(r'^[a-z0-9][a-z0-9-]*$')
HEADING = re.compile(r'^#{1,6} .*$', re.M)
# Document budget (docs/DOCUMENTATION.md#document-budget). Raising a limit is an owner decision.
LINE_LIMITS = {'PROJECT_PROFILE.md': 250, 'docs/OPEN_WORK.md': 150}
UNDATED_HEADINGS = ('PROJECT_PROFILE.md',)
# Second always-on instruction files that agents load beside AGENTS.md (docs/AGENT_TOOLS.md).
POINTER_FILES = ('GEMINI.md', '.github/copilot-instructions.md')
POINTER_MAX_LINES = 10


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prose(text):
    """Text outside code fences and inline code, where links and placeholders are meaningful."""
    return INLINE_CODE.sub('', FENCE.sub('', text))


def rel(path):
    return path.relative_to(root).as_posix()


def walk(include_repo_only, manifest):
    repo_only = tuple(manifest.get('repo_only', []))
    for path in sorted(root.rglob('*')):
        parts = path.relative_to(root).parts
        if not path.is_file() or SKIP_DIRS.intersection(parts):
            continue
        if not include_repo_only and rel(path).startswith(repo_only):
            continue
        yield path


def frontmatter(text):
    if not text.startswith('---\n') or '\n---\n' not in text[4:]:
        return {}
    block = text[4:text.index('\n---\n', 4)]
    fields = {}
    for line in block.splitlines():
        key, sep, value = line.partition(':')
        if sep:
            fields[key.strip()] = value.strip()
    return fields


def tool_paths(manifest):
    """Path prefixes per agent tool; a file no tool names is agent-neutral and installed for every project."""
    return {t: tuple(v['paths']) for t, v in manifest.get('tools', {}).items()}


def adopted_tools(manifest, record):
    """The tools a project uses: recorded at install, or every tool for an install that recorded none."""
    return set((record or {}).get('tools') or manifest.get('tools', {}))


def for_tools(manifest, path, tools):
    """Whether a packaged path belongs in a project that uses these tools."""
    owners = [t for t, prefixes in tool_paths(manifest).items() if path.startswith(prefixes)]
    return not owners or any(t in tools for t in owners)


def expected_adapters(manifest, errors, tools=None):
    """Map of adapter path -> generated SKILL.md content for every procedure."""
    expected = {}
    source_dir = root / manifest['procedures']
    for source in sorted(source_dir.glob('*.md')):
        fields = frontmatter(source.read_text())
        name, description = fields.get('name', ''), fields.get('description', '')
        if not NAME.match(name) or name != source.stem or not description:
            errors.append(f'{rel(source)}: frontmatter needs name matching the filename and a description')
            continue
        for adapter in manifest['adapters']:
            if tools is not None and not for_tools(manifest, adapter['dir'] + '/', tools):
                continue
            expected[f"{adapter['dir']}/{name}/SKILL.md"] = (
                f'---\nname: {name}\ndescription: {json.dumps(description)}\n---\n'
                f'<!-- Generated by check_package.py --sync-adapters from {rel(source)}. Edit that file, then regenerate. -->\n\n'
                f'# {name}\n\n'
                f'Read `{rel(source)}` from the repository root and follow it exactly. '
                'That file is the authoritative procedure; this wrapper only makes it discoverable as a skill.\n')
    return expected


def existing_adapters(manifest, tools=None):
    return {rel(p) for adapter in manifest['adapters'] for p in (root / adapter['dir']).glob('*/SKILL.md')
            if tools is None or for_tools(manifest, adapter['dir'] + '/', tools)}


def checkout_tools(manifest, template):
    """Tools whose adapters this checkout keeps: all of them in the template repository, else the recorded ones."""
    return None if template else adopted_tools(manifest, manifest.get('installed'))


def sync_adapters(manifest, errors, template=True):
    agents = generate_agents(root / 'AGENTS.md', manifest, modules_in_checkout(manifest, template))
    if agents is not None and agents != (root / 'AGENTS.md').read_text():
        (root / 'AGENTS.md').write_text(agents)
        print('Regenerated the AGENTS.md routing and procedure tables')
    tools = checkout_tools(manifest, template)
    expected = expected_adapters(manifest, errors, tools)
    for path in existing_adapters(manifest, tools) - expected.keys():
        (root / path).unlink()
        print('Removed orphaned adapter: ' + path)
    for path, content in expected.items():
        target = root / path
        if not target.is_file() or target.read_text() != content:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
            print('Wrote adapter: ' + path)


def update_manifest(manifest, errors):
    expected = expected_adapters(manifest, errors)
    entries = [e for e in manifest['files'] if e['kind'] != 'adapter' or e['path'] in expected]
    listed = {e['path'] for e in entries}
    entries += [{'path': p, 'kind': 'adapter'} for p in sorted(expected.keys() - listed)]
    for entry in entries:
        path = root / entry['path']
        if path.is_file():
            entry['bytes'], entry['sha256'] = path.stat().st_size, sha256(path)
        else:
            errors.append('Manifest entry has no file: ' + entry['path'])
    manifest['files'] = entries
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Updated manifest: {len(entries)} entries.')


def source_identity():
    """Commit and dirty state of this package checkout, recorded so later upgrades know where to diff from."""
    def git(*args):
        result = subprocess.run(['git', '-C', str(root), *args], capture_output=True, text=True)
        return result.stdout.strip() if result.returncode == 0 else None
    commit = git('rev-parse', 'HEAD')
    status = git('status', '--porcelain')
    return {'repository': git('config', '--get', 'remote.origin.url') or 'unknown', 'commit': commit or 'unknown',
            'dirty': None if status is None else bool(status), 'date': date.today().isoformat()}


GENERATED = re.compile(r'(<!-- generated: (\w+)\b[^\n]*-->\n)(.*?)(<!-- end generated: \2 -->)', re.S)
TABLE_HEADERS = {
    'routing': '| When the change touches… | Read before | Update after |\n|---|---|---|\n',
    'procedures': '| Procedure | Use when |\n|---|---|\n',
}


def render_block(manifest, name, modules):
    """A generated AGENTS.md block: the manifest's rows for the given modules, in manifest order."""
    tables = manifest.get('agents_tables', {})
    rows = [r['row'] for r in tables.get(name, []) if r['module'] in modules]
    text = TABLE_HEADERS[name] + ''.join(row + '\n' for row in rows)
    notes = [r['row'] for r in tables.get(name + '_notes', []) if r['module'] in modules]
    if notes:
        text += '\n' + ' '.join(notes) + '\n'
    return text


def generate_agents(path, manifest, modules):
    """AGENTS.md text with every generated block rendered for these modules, or None if there is no file."""
    if not path.is_file():
        return None
    return GENERATED.sub(lambda m: m.group(1) + render_block(manifest, m.group(2), modules) + m.group(4), path.read_text())


def modules_in_checkout(manifest, template):
    """Modules present in this checkout: all of them in the template repository or a 2.x install."""
    record = None if template else manifest.get('installed')
    return set(record['modules']) if record else set(manifest.get('modules', {})) or {'core'}


# Who each tier is for, in a few words; the tier table in PROJECT_PROFILE.md is the definition.
TIER_AUDIENCE = {'prototype': 'small tools and experiments', 'internal': 'trusted users, data that matters',
                 'production': 'external users or uptime commitments', 'enterprise': 'roles, traceability, supply chain'}


def tier_choice(manifest, target):
    """The message when a fresh install names no tier: nothing is copied, and the tiers and the rerun command are shown."""
    lines, previous = ['Choose a tier; nothing was installed.'], set()
    for tier, mods in manifest['tiers'].items():
        added = [m for m in mods if m not in previous] if previous else mods
        lines.append(f"  {tier:<11} {'+ ' if previous else ''}{', '.join(added)}: {TIER_AUDIENCE.get(tier, '')}")
        previous = set(mods)
    lines += [f"Features: {', '.join(manifest['features'])}",
              f'Example: --install {target} --tier internal --features ui',
              'Preview first with --dry-run. The 2.x set (every module except Enterprise): --all']
    return '\n'.join(lines)


def resolve_modules(manifest, tier, features, everything=False):
    """Modules for a tier plus features, or with everything=True the 2.x set: every module except enterprise.
    Enterprise controls are only added by choosing that tier."""
    unknown = [f for f in features if f not in manifest['features']]
    if unknown:
        sys.exit(f"Unknown feature(s): {', '.join(unknown)}; choose from {', '.join(manifest['features'])}")
    modules = set(m for m in manifest['modules'] if m != 'enterprise') if everything else set(manifest['tiers'][tier]) if tier else set()
    for feature in features:
        modules.update(manifest['features'][feature])
    return sorted(modules)


def add_profile_rows(profile, manifest, modules):
    """Add the installed modules' command-inventory rows (for example the enterprise release gates) to the project's
    PROJECT_PROFILE.md once, before the Guidance integrity row. Rows whose purpose is already listed are left alone,
    so an owner's filled-in commands are never overwritten. Returns the purposes added."""
    if not profile.is_file():
        return []
    text = profile.read_text()
    purpose = lambda row: row.strip().strip('|').split('|')[0].strip()
    present = {purpose(l) for l in text.splitlines() if l.lstrip().startswith('|')}
    new = [r['row'] for r in manifest.get('profile_rows', []) if r['module'] in modules and purpose(r['row']) not in present]
    if not new:
        return []
    anchor = next((l for l in text.splitlines() if l.startswith('| Guidance integrity |')), None)
    if anchor is None:
        return []
    profile.write_text(text.replace(anchor, '\n'.join(new) + '\n' + anchor, 1))
    return [purpose(r) for r in new]


def enterprise_notes():
    """Reported, not enforced: commits without a ticket ID, a missing CODEOWNERS file and CI without --verify."""
    notes = []
    doc = root / 'docs' / 'ENTERPRISE.md'
    row = next((l for l in doc.read_text().splitlines() if l.startswith('| Ticket ID pattern')), '') if doc.is_file() else ''
    pattern = INLINE_CODE.findall(row)
    if pattern:
        try:
            ticket = re.compile(pattern[0].strip('`'))
        except re.error:
            notes.append(f'Enterprise: the ticket ID pattern {pattern[0]} is not a valid regular expression')
            ticket = None
        log = subprocess.run(['git', '-C', str(root), 'log', '-20', '--format=%H%x00%B%x01'], capture_output=True, text=True)
        commits = [c for c in log.stdout.split('\x01') if c.strip()] if log.returncode == 0 else []
        missing = [c.strip().split('\x00')[0][:7] for c in commits if ticket and not ticket.search(c.split('\x00', 1)[-1])]
        if ticket and commits:
            notes.append(f'Enterprise: {len(missing)} of the last {len(commits)} commits lack a ticket ID' + (f" ({', '.join(missing[:5])})" if missing else ''))
    else:
        notes.append('Enterprise: no ticket ID pattern is set in docs/ENTERPRISE.md, so traceability is not reported')
    if not any((root / p).is_file() for p in ('CODEOWNERS', '.github/CODEOWNERS', 'docs/CODEOWNERS')):
        notes.append('Enterprise: no CODEOWNERS file; approvals rely on the hosting service settings alone')
    workflows = list((root / '.github' / 'workflows').glob('*.y*ml')) if (root / '.github' / 'workflows').is_dir() else []
    if not any('check_package.py --verify' in w.read_text(errors='replace') for w in workflows):
        notes.append('Enterprise: no CI workflow runs check_package.py --verify, so there is no CI verification receipt')
    return notes


def install(manifest, target, force, tier=None, features=(), everything=False, dry_run=False, tools=()):
    """Copy the core and the modules for a tier and features. A fresh install must name a tier, or --all for the 2.x
    set. Rerunning on a project keeps its recorded modules and adds only what is named; it never overwrites existing
    files unless --force is given. dry_run lists what would be copied and writes nothing."""
    target = Path(target).resolve()
    if not target.is_dir() or target == root:
        sys.exit(f'Install target must be an existing directory other than this package: {target}')
    previous = {}
    if (target / manifest_path.name).is_file():
        previous = json.loads((target / manifest_path.name).read_text()).get('installed', {})
    if not (tier or everything or previous.get('modules')):
        sys.exit(tier_choice(manifest, target))
    modules = sorted(set(resolve_modules(manifest, tier, list(features), everything)) | set(previous.get('modules', [])))
    unknown = [t for t in tools if t not in manifest.get('tools', {})]
    if unknown:
        sys.exit(f"Unknown tool(s): {', '.join(unknown)}; choose from {', '.join(manifest.get('tools', {}))}")
    # Named tools add to the recorded ones; an install that names none, now or before, gets every tool's files.
    chosen = sorted(set(tools) | set(previous.get('tools', []))) if tools or previous.get('tools') else sorted(manifest.get('tools', {}))
    wanted = [e['path'] for e in manifest['files'] if e.get('module', 'core') in modules and for_tools(manifest, e['path'], chosen)]
    if dry_run:
        new = [p for p in wanted + [manifest_path.name] if force or not (target / p).exists()]
        print(f"Would install modules: {', '.join(modules)}" + (f' (tier {tier or previous.get("tier")})' if tier or previous.get('tier') else '')
              + f"; tools: {', '.join(chosen)}")
        print(f'Would copy {len(new)} files into {target}' + (':\n  ' + '\n  '.join(new) if new else '.'))
        kept = len(wanted) + 1 - len(new)
        if kept:
            print(f'Would skip {kept} existing files.')
        print('Nothing was written (--dry-run).')
        return
    copied, skipped = [], []
    for path in wanted + [manifest_path.name]:
        dest = target / path
        if dest.exists() and not force:
            skipped.append(path)
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(root / path, dest)
        copied.append(path)
    record = json.loads((target / manifest_path.name).read_text())
    if manifest_path.name in copied:
        record['installed_from'] = source_identity()
    record['installed'] = {
        'tier': tier or previous.get('tier'),
        'features': sorted(set(features) | set(previous.get('features', []))),
        'modules': modules,
        'tools': chosen,
    }
    (target / manifest_path.name).write_text(json.dumps(record, indent=2) + '\n')
    agents = generate_agents(target / 'AGENTS.md', manifest, set(modules))
    if agents is not None:
        (target / 'AGENTS.md').write_text(agents)
    added = add_profile_rows(target / 'PROJECT_PROFILE.md', manifest, set(modules))
    if added:
        print('Added command-inventory rows: ' + ', '.join(added))
    print(f"Installed modules: {', '.join(modules)}" + (f" (tier {record['installed']['tier']})" if record['installed']['tier'] else '')
          + f"; tools: {', '.join(manifest['tools'][t]['name'] for t in chosen)}")
    print(f'Copied {len(copied)} files into {target}.')
    if skipped:
        print('Skipped existing files (merge by hand or rerun with --force):\n  ' + '\n  '.join(skipped))
    print('Next: ask your agent to "bootstrap the project guidance" (docs/procedures/bootstrap-project.md).')


# Upgrade planning (docs/procedures/upgrade-guidance.md). Kinds a project fills in are never merged automatically.
FILLED_KINDS = ('template', 'register', 'profile', 'entry')
PLAN_ORDER = ('replace', 'add', 'merge', 'conflict', 'review', 'remove', 'keep', 'absent')


def package_git(*args):
    result = subprocess.run(['git', '-C', str(root), *args], capture_output=True, text=True)
    return result.stdout if result.returncode == 0 else None


def project_record(target):
    """The project's installed manifest, its recorded modules (the 2.x set when none are recorded) and source commit."""
    path = target / manifest_path.name
    if not path.is_file():
        sys.exit(f'{target} has no {manifest_path.name}, so it is not a package-layout install. '
                 'Follow docs/procedures/upgrade-guidance.md by hand.')
    record = json.loads(path.read_text())
    new = json.loads(manifest_path.read_text())
    modules = set(record.get('installed', {}).get('modules') or (m for m in new['modules'] if m != 'enterprise'))
    return record, modules, record.get('installed_from', {}).get('commit')


def plan_tools(manifest, record):
    return adopted_tools(manifest, record.get('installed'))


def effective(path, text, manifest, modules):
    """A packaged file as an install writes it: AGENTS.md has its generated tables rendered for the project's modules."""
    if path != 'AGENTS.md' or text is None:
        return text
    return GENERATED.sub(lambda m: m.group(1) + render_block(manifest, m.group(2), modules) + m.group(4), text)


def unified(path, old, new):
    """A git-apply patch for one file; None for either side means the file is absent."""
    def lines(text):
        out = (text or '').splitlines(keepends=True)
        if out and not out[-1].endswith('\n'):
            out[-1] += '\n\\ No newline at end of file\n'
        return out
    head = [f'diff --git a/{path} b/{path}\n']
    head += ['new file mode 100644\n'] if old is None else ['deleted file mode 100644\n'] if new is None else []
    body = list(difflib.unified_diff(lines(old), lines(new), '/dev/null' if old is None else 'a/' + path,
                                     '/dev/null' if new is None else 'b/' + path))
    return ''.join(head + body) if body else ''


def plan_upgrade(manifest, target, patch=None):
    """Compare the installed baseline, the project's files and this package, and say what an upgrade would do to each
    packaged file. Writes nothing in the project; with patch, writes the proposed changes there as a git-apply patch."""
    target = Path(target).resolve()
    if not target.is_dir() or target == root:
        sys.exit(f'Upgrade target must be an existing directory other than this package: {target}')
    if patch and Path(patch).resolve().is_relative_to(target):
        sys.exit('Write the patch outside the project, so planning changes nothing in it.')
    record, modules, base_commit = project_record(target)
    old_manifest = record
    baseline = {e['path']: e for e in record.get('files', [])}
    tools = plan_tools(manifest, record)
    wanted = {e['path']: e for e in manifest['files'] if e.get('module', 'core') in modules and for_tools(manifest, e['path'], tools)}
    have_base = bool(base_commit and package_git('cat-file', '-e', f'{base_commit}^{{commit}}') is not None)
    source = source_identity()
    rows, diffs, blocked = [], [], []

    def base_text(path):
        text = package_git('show', f'{base_commit}:{path}') if have_base else None
        return effective(path, text, old_manifest, modules)

    for path in sorted(baseline.keys() | wanted.keys()):
        entry = wanted.get(path) or baseline[path]
        kind = entry.get('kind', '')
        file = target / path
        mine = file.read_text() if file.is_file() else None
        new = effective(path, (root / path).read_text(), manifest, modules) if path in wanted else None
        old = base_text(path) if path in baseline else None
        if old is None and path in baseline and mine is not None and not have_base:
            # No baseline text: hashes still say whether either side changed.
            same_base = sha256(file) == baseline[path].get('sha256')
            old = mine if same_base else None
        upstream = new != old if path in baseline else True
        modified = mine != old if path in baseline and old is not None else None
        if mine == new:
            if new is not None:
                rows.append(('keep', path, kind, ''))
            continue
        elif not upstream:
            continue
        elif mine is None:
            action, note = ('add', '') if path not in baseline else ('absent', 'removed here; upstream changed it')
            if path in baseline and new is None:
                continue
        elif path not in baseline:
            action, note = 'conflict', 'the project has its own file at this path'
        elif new is None:
            action, note = ('remove', 'removed upstream') if modified is False else ('review', 'removed upstream; modified here')
        elif modified is False:
            action, note = 'replace', ''
        elif modified is None:
            action, note = 'review', f'no baseline text for commit {base_commit or "unrecorded"}; merge by hand'
        elif kind in FILLED_KINDS and path != 'AGENTS.md':
            action, note = 'review', f'{kind} filled in here; carry structural changes by hand'
        else:
            with tempfile.TemporaryDirectory() as tmp:
                names = []
                for name, text in (('mine', mine), ('base', old), ('new', new)):
                    (Path(tmp) / name).write_text(text)
                    names.append(str(Path(tmp) / name))
                merged = subprocess.run(['git', 'merge-file', '-p', '-L', 'project', '-L', 'installed', '-L', 'upstream', *names],
                                        capture_output=True, text=True)
            if merged.returncode == 0:
                action, note = 'merge', 'project changes kept'
                diffs.append(unified(path, mine, merged.stdout))
            else:
                hunks = merged.returncode if merged.returncode > 0 else '?'
                action, note = 'conflict', f'{hunks} conflicting hunk(s) with local changes'
        if action in ('replace', 'add', 'remove'):
            diffs.append(unified(path, mine, new))
        if action in ('replace', 'add', 'remove', 'merge'):
            parent = next(p for p in [file, *file.parents] if p.exists())
            if not os.access(parent if parent.is_dir() else parent.parent, os.W_OK):
                blocked.append(path)
        rows.append((action, path, kind, note))

    proposed = dict(manifest, installed_from=source)
    proposed['installed'] = dict(record.get('installed') or {'tier': None, 'features': []}, modules=sorted(modules), tools=sorted(tools))
    diffs.append(unified(manifest_path.name, (target / manifest_path.name).read_text(), json.dumps(proposed, indent=2) + '\n'))

    print(f"Upgrade plan for {target}: installed from {(base_commit or 'an unrecorded commit')[:12]}, "
          f"package at {source['commit'][:12]}{' (dirty checkout)' if source['dirty'] else ''}. Nothing was written to the project.")
    if not have_base:
        print('  The installed commit is not in this checkout, so local changes cannot be merged automatically.')
    labels = {'replace': 'Replace (unmodified here)', 'add': 'Add (new upstream)', 'merge': 'Merge (both changed; merges cleanly)',
              'conflict': 'Conflict (merge by hand)', 'review': 'Review (by hand)', 'remove': 'Remove (removed upstream)',
              'keep': 'Already current', 'absent': 'Absent here (record the exclusion or restore it)'}
    for action in PLAN_ORDER:
        group = [r for r in rows if r[0] == action]
        if group:
            print(f'{labels[action]}: {len(group)}')
            for _, path, kind, note in group if action != 'keep' else ():
                print(f'  {path}' + (f' ({note})' if note else ''))
    if any(r[0] in ('conflict', 'review') for r in rows) and have_base:
        print(f"Upstream change for a file: git -C {root} diff {base_commit[:12]} {source['commit'][:12]} -- PATH")
    if any(r[1].startswith(('.agents/', '.claude/', '.codex/')) or r[2] == 'procedure' for r in rows if r[0] != 'keep'):
        print('After merging procedures, regenerate the skill copies: python3 check_package.py --sync-adapters')
    if blocked:
        print('Not writable here (ask the user to apply these): ' + ', '.join(blocked))
    if patch:
        Path(patch).write_text(''.join(d for d in diffs if d))
        print(f'Proposed patch (replace, add, merge and remove, plus the new manifest): {Path(patch).resolve()}')
    print('This is a plan only. Show it to the user with your questions about each conflict and review item, then stop. '
          'Apply nothing, including the replace and add changes, until the user approves. After applying, run this '
          f"checkout's checker, not the project's copy: python3 {root / 'check_package.py'} --check-upgrade {target} "
          f"--since {(subprocess.run(['git', '-C', str(target), 'rev-parse', '--short', 'HEAD'], capture_output=True, text=True).stdout.strip() or '<commit before the upgrade>')}")


OPEN_ITEM = re.compile(r'^\|\s*([A-Z][A-Z0-9]*-\d+)\s*\|(.*)$', re.M)
REVISION = re.compile(r'\b(?=[0-9a-f]*\d)(?=[0-9a-f]*[a-f])[0-9a-f]{7,40}\b')


def check_upgrade(target, since='HEAD'):
    """After an upgrade is applied, compare the project with its pre-upgrade commit: open items, deployed revisions,
    references to deleted scripts and local changes to packaged files must survive. Exits 1 on a problem."""
    target = Path(target).resolve()

    def git(*args):
        result = subprocess.run(['git', '-C', str(target), *args], capture_output=True, text=True)
        if result.returncode:
            sys.exit(f"git {' '.join(args)} failed in {target}: {result.stderr.strip()}")
        return result.stdout

    before_files = [p for p in git('ls-tree', '-r', '--name-only', since).splitlines()]
    shown = lambda p: subprocess.run(['git', '-C', str(target), 'show', f'{since}:{p}'], capture_output=True, text=True).stdout
    now_files = [p for p in git('ls-files', '--cached', '--others', '--exclude-standard').splitlines() if (target / p).is_file()]
    now_docs = '\n'.join((target / p).read_text(errors='replace') for p in now_files if p.endswith('.md'))
    problems = []
    open_before, revisions = set(), set()
    for path in (p for p in before_files if p.endswith('.md')):
        text = shown(path)
        open_before |= {m.group(1) for m in OPEN_ITEM.finditer(text) if re.search(r'(?i)\|\s*open\b', '|' + m.group(2))}
        revisions |= {r for line in text.splitlines() if re.search(r'(?i)deploy', line) for r in REVISION.findall(line)}
    still_open = {m.group(1) for m in OPEN_ITEM.finditer(now_docs) if re.search(r'(?i)\|\s*open\b', '|' + m.group(2))}
    lost = sorted(i for i in open_before if not re.search(rf'\b{re.escape(i)}\b', now_docs))
    closed = sorted(i for i in open_before - still_open if i not in lost)
    if lost:
        problems.append('Open items no longer in any document: ' + ', '.join(lost))
    if closed:
        problems.append('Open items no longer marked open (an upgrade does not close them): ' + ', '.join(closed))
    missing = sorted(r for r in revisions if r not in now_docs)
    if missing:
        problems.append('Deployed revisions no longer in any document: ' + ', '.join(missing))
    deleted = sorted(set(before_files) - set(now_files))
    code = [p for p in now_files if not p.endswith(('.md', '.json'))]
    for gone in deleted:
        name = Path(gone).name
        users = [p for p in code if name in (target / p).read_text(errors='replace')]
        if users:
            problems.append(f'{gone} was deleted but {", ".join(users)} still names it')
    record = json.loads(shown(manifest_path.name) or '{}')
    commit = record.get('installed_from', {}).get('commit')
    modules = set(record.get('installed', {}).get('modules') or (m for m in record.get('modules', {}) if m != 'enterprise'))
    packaged = [e['path'] for e in record.get('files', []) if e['path'] in before_files
                and (e.get('kind') not in FILLED_KINDS or e['path'] == 'AGENTS.md')]
    flat = lambda text: ' '.join(text.split())
    hashes = {e['path']: e.get('sha256') for e in record.get('files', [])}
    unchecked = []
    for path in packaged:
        base = effective(path, package_git('show', f'{commit}:{path}') if commit else None, record, modules)
        mine_before = shown(path)
        if base is None:
            # Without the installed text, a file the project changed cannot be checked; say so rather than pass it.
            if hashlib.sha256(mine_before.encode()).hexdigest() != hashes.get(path):
                unchecked.append(path)
            continue
        if mine_before == base:
            continue
        now = flat((target / path).read_text()) if (target / path).is_file() else ''
        base_lines = base.splitlines()
        dropped = []
        for line in set(mine_before.splitlines()) - set(base_lines):
            # Each run of words the line adds to its closest installed line must survive verbatim, wherever it was merged.
            close = difflib.get_close_matches(line, base_lines, n=1, cutoff=0.6)
            words, old_words = line.split(), (close[0].split() if close else [])
            runs = [' '.join(words[j1:j2]) for op, _, _, j1, j2 in difflib.SequenceMatcher(None, old_words, words).get_opcodes()
                    if op in ('insert', 'replace')]
            runs = [r.strip('-*|# ') for r in runs if len(r.strip('-*|# ')) > 3]
            if any(flat(r) not in now for r in runs):
                dropped.append(line)
        if dropped:
            problems.append(f'{path}: {len(dropped)} local change(s) not found verbatim, first: {dropped[0].strip()[:80]}')
    if unchecked:
        problems.append(f"Could not check local changes in {', '.join(unchecked)}: the installed commit "
                        f"{(commit or 'unrecorded')[:12]} is not in this checkout. Run the check from the guidance checkout: "
                        f"python3 <guidance checkout>/check_package.py --check-upgrade {target} --since {since}")
    for path in now_files:
        if path.endswith('.md') and re.search(r'(?m)^(<{7} |>{7} )', (target / path).read_text(errors='replace')):
            problems.append(f'{path}: unresolved merge conflict markers')
    if problems:
        print('\n'.join(problems))
    print(f"Upgrade check against {since}: {len(open_before)} open items, {len(revisions)} deployed revisions, "
          f"{len(deleted)} deleted files, {len(packaged)} packaged files checked; "
          + (f'{len(problems)} problem(s).' if problems else 'nothing lost.'))
    if problems:
        sys.exit(1)


EXCLUDED_ROW = re.compile(r'^\|\s*Excluded guidance\b.*$', re.M)


def recorded_exclusions(profile):
    """Paths named in backticks in PROJECT_PROFILE.md's Excluded guidance row; a path ending in / covers a folder.
    The row's prose is the owner's rationale; only the backticked paths are read."""
    row = EXCLUDED_ROW.search(profile.read_text()) if profile.is_file() else None
    paths = [t.strip('`').strip().removeprefix('./') for t in INLINE_CODE.findall(row.group(0))] if row else []
    return tuple(p for p in paths if '/' in p or '.' in p)


def excluded(path, exclusions):
    return any(path == e or (e.endswith('/') and path.startswith(e)) for e in exclusions)


def check_links(files, errors, uninstalled=frozenset()):
    """Fail on links that resolve nowhere. Links to packaged files of modules this project did not install are
    expected (the shared documents mention every module) and are counted instead. Returns that count."""
    skipped = 0
    for path in files:
        if path.suffix != '.md':
            continue
        for link in LINK.findall(prose(path.read_text())):
            if '://' in link or link.startswith(('#', 'mailto:')):
                continue
            target = (path.parent / link.split('#')[0]).resolve()
            if target.is_relative_to(root) and not target.exists() and rel(target) in uninstalled:
                skipped += 1
            elif not target.is_relative_to(root) or not target.exists():
                errors.append(f'{rel(path)}: unresolved or escaping link {link}')
    return skipped


def check_shims(files, errors, exempt, claude=True):
    for path in files:
        if not claude:
            break
        if path.name == 'AGENTS.md' and not rel(path).startswith(exempt):
            shim = path.with_name('CLAUDE.md')
            if not shim.is_file() or '@AGENTS.md' not in shim.read_text():
                errors.append(f'{rel(path)}: needs a sibling CLAUDE.md containing @AGENTS.md for Claude Code')


def check_modules(manifest, errors):
    """Template mode: every file has a known module, tiers and features name known modules, and each skill
    adapter belongs to the same module as its procedure."""
    known = set(manifest.get('modules', {}))
    modules_of = {e['path']: e.get('module') for e in manifest['files']}
    for path, module in modules_of.items():
        if module not in known:
            errors.append(f'{path}: manifest module {module!r} is not defined under "modules"')
    for group in ('tiers', 'features'):
        for name, mods in manifest.get(group, {}).items():
            for m in mods:
                if m not in known:
                    errors.append(f'{group} {name!r} names unknown module {m!r}')
    for path, module in modules_of.items():
        if path.endswith('/SKILL.md'):
            procedure = f"{manifest['procedures']}/{path.split('/')[-2]}.md"
            if modules_of.get(procedure) != module:
                errors.append(f'{path}: adapter module {module!r} differs from its procedure {procedure} ({modules_of.get(procedure)!r})')


