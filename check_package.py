#!/usr/bin/env python3
"""Install, integrity, link, adapter and placeholder checks for the reusable guidance package.

Template mode (MAINTAINING.md present) checks the package itself; project mode checks an installed copy.
Only --install, --sync-adapters and --update-manifest write files.
"""
from pathlib import Path
import argparse, hashlib, json, re, shutil, subprocess, sys

root = Path(__file__).resolve().parent
manifest_path = root / 'PACKAGE_MANIFEST.json'
STAGE_MARKER = '<!-- stage: release -->'
SKIP_DIRS = {'.git', '__pycache__'}
PLACEHOLDER = re.compile(r'\{\{[^}]+\}\}')
LINK = re.compile(r'\]\(([^)\s]+)(?:\s+"[^"]*")?\)')
FENCE = re.compile(r'^(```|~~~).*?^\1[ \t]*$', re.M | re.S)
INLINE_CODE = re.compile(r'`[^`\n]*`')
DATED = re.compile(r'\b20\d\d-\d\d-\d\d\b')
NAME = re.compile(r'^[a-z0-9][a-z0-9-]*$')


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prose(text):
    """Text outside code fences and inline code, where links and placeholders are meaningful."""
    return INLINE_CODE.sub('', FENCE.sub('', text))


def rel(path):
    return path.relative_to(root).as_posix()


def walk(include_repo_only, manifest):
    repo_only = tuple(manifest.get('repo_only', []))
    for path in sorted(root.rglob('*')):
        parts = path.relative_to(root).parts
        if not path.is_file() or SKIP_DIRS.intersection(parts):
            continue
        if not include_repo_only and rel(path).startswith(repo_only):
            continue
        yield path


def frontmatter(text):
    if not text.startswith('---\n') or '\n---\n' not in text[4:]:
        return {}
    block = text[4:text.index('\n---\n', 4)]
    fields = {}
    for line in block.splitlines():
        key, sep, value = line.partition(':')
        if sep:
            fields[key.strip()] = value.strip()
    return fields


def expected_adapters(manifest, errors):
    """Map of adapter path -> generated SKILL.md content for every procedure."""
    expected = {}
    source_dir = root / manifest['procedures']
    for source in sorted(source_dir.glob('*.md')):
        fields = frontmatter(source.read_text())
        name, description = fields.get('name', ''), fields.get('description', '')
        if not NAME.match(name) or name != source.stem or not description:
            errors.append(f'{rel(source)}: frontmatter needs name matching the filename and a description')
            continue
        for adapter in manifest['adapters']:
            expected[f"{adapter['dir']}/{name}/SKILL.md"] = (
                f'---\nname: {name}\ndescription: {json.dumps(description)}\n---\n'
                f'<!-- Generated by check_package.py --sync-adapters from {rel(source)}. Edit that file, then regenerate. -->\n\n'
                f'# {name}\n\n'
                f'Read `{rel(source)}` from the repository root and follow it exactly. '
                f"That file is the authoritative procedure; this wrapper only makes it discoverable to {adapter['tools']}.\n")
    return expected


def existing_adapters(manifest):
    return {rel(p) for adapter in manifest['adapters'] for p in (root / adapter['dir']).glob('*/SKILL.md')}


def sync_adapters(manifest, errors):
    expected = expected_adapters(manifest, errors)
    for path in existing_adapters(manifest) - expected.keys():
        (root / path).unlink()
        print('Removed orphaned adapter: ' + path)
    for path, content in expected.items():
        target = root / path
        if not target.is_file() or target.read_text() != content:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
            print('Wrote adapter: ' + path)


def update_manifest(manifest, errors):
    expected = expected_adapters(manifest, errors)
    entries = [e for e in manifest['files'] if e['kind'] != 'adapter' or e['path'] in expected]
    listed = {e['path'] for e in entries}
    entries += [{'path': p, 'kind': 'adapter'} for p in sorted(expected.keys() - listed)]
    for entry in entries:
        path = root / entry['path']
        if path.is_file():
            entry['bytes'], entry['sha256'] = path.stat().st_size, sha256(path)
        else:
            errors.append('Manifest entry has no file: ' + entry['path'])
    manifest['files'] = entries
    manifest_path.write_text(json.dumps(manifest, indent=2) + '\n')
    print(f'Updated manifest: {len(entries)} entries.')


def install(manifest, target, force):
    target = Path(target).resolve()
    if not target.is_dir() or target == root:
        sys.exit(f'Install target must be an existing directory other than this package: {target}')
    copied, skipped = [], []
    for path in [e['path'] for e in manifest['files']] + [manifest_path.name]:
        dest = target / path
        if dest.exists() and not force:
            skipped.append(path)
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(root / path, dest)
        copied.append(path)
    print(f'Copied {len(copied)} files into {target}.')
    if skipped:
        print('Skipped existing files (merge by hand or rerun with --force):\n  ' + '\n  '.join(skipped))
    print('Next: ask your agent to "bootstrap the project guidance" (docs/procedures/bootstrap-project.md).')


def check_links(files, errors):
    for path in files:
        if path.suffix != '.md':
            continue
        for link in LINK.findall(prose(path.read_text())):
            if '://' in link or link.startswith(('#', 'mailto:')):
                continue
            target = (path.parent / link.split('#')[0]).resolve()
            if not target.is_relative_to(root) or not target.exists():
                errors.append(f'{rel(path)}: unresolved or escaping link {link}')


def check_shims(files, errors):
    for path in files:
        if path.name == 'AGENTS.md':
            shim = path.with_name('CLAUDE.md')
            if not shim.is_file() or '@AGENTS.md' not in shim.read_text():
                errors.append(f'{rel(path)}: needs a sibling CLAUDE.md containing @AGENTS.md for Claude Code')


def check_adapters(manifest, errors):
    expected = expected_adapters(manifest, errors)
    for path in existing_adapters(manifest) - expected.keys():
        errors.append(f'Orphaned adapter {path}; run --sync-adapters')
    for path, content in expected.items():
        target = root / path
        if not target.is_file() or target.read_text() != content:
            errors.append(f'Stale or missing adapter {path}; run --sync-adapters')


def placeholders(files, manifest):
    """Per-file (code-stage, release-stage) placeholder counts."""
    stages = {e['path']: e.get('stage') for e in manifest['files']}
    counts = {}
    for path in files:
        if path.suffix != '.md':
            continue
        text = path.read_text()
        before, marker, after = text.partition(STAGE_MARKER)
        if stages.get(rel(path)) == 'code':
            code, release = len(PLACEHOLDER.findall(prose(before))), len(PLACEHOLDER.findall(prose(after)))
        else:
            code, release = 0, len(PLACEHOLDER.findall(prose(text)))
        if code or release:
            counts[rel(path)] = (code, release)
    return counts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--template', action='store_true', help='force template mode')
    mode.add_argument('--project', action='store_true', help='force project mode')
    parser.add_argument('--require', choices=['code', 'release'], help='fail if placeholders remain at this stage')
    parser.add_argument('--install', metavar='DIR', help='copy packaged files into a project directory')
    parser.add_argument('--force', action='store_true', help='with --install, overwrite existing files')
    parser.add_argument('--sync-adapters', action='store_true', help='regenerate skill wrappers from procedures')
    parser.add_argument('--update-manifest', action='store_true', help='refresh manifest hashes (template mode)')
    args = parser.parse_args()

    manifest = json.loads(manifest_path.read_text())
    template = args.template or (not args.project and (root / 'MAINTAINING.md').exists())
    errors = []

    if args.install:
        install(manifest, args.install, args.force)
        return
    if args.sync_adapters:
        sync_adapters(manifest, errors)
    if args.update_manifest:
        if not template:
            sys.exit('--update-manifest is for the template repository; project copies keep upstream hashes.')
        update_manifest(manifest, errors)

    files = list(walk(include_repo_only=template, manifest=manifest))
    check_links(files, errors)
    check_shims(files, errors)
    check_adapters(manifest, errors)
    notes = []
    listed = {e['path']: e for e in manifest['files']}
    if template:
        for path, entry in listed.items():
            if not (root / path).is_file() or sha256(root / path) != entry.get('sha256'):
                errors.append(f'Missing or changed packaged file {path}; review, then run --update-manifest')
            if entry['kind'] == 'register' and (root / path).is_file() and DATED.search(prose((root / path).read_text())):
                errors.append(f'{path}: template registers must stay empty; move history to MAINTAINING.md')
        for path in walk(include_repo_only=False, manifest=manifest):
            if rel(path) not in listed and path != manifest_path:
                errors.append(f'Unlisted file {rel(path)}; add it to the manifest or to repo_only')
        scenarios = root / 'maintainer' / 'run_scenario.py'
        if scenarios.is_file():
            result = subprocess.run([sys.executable, str(scenarios), '--check'], capture_output=True, text=True)
            if result.returncode:
                errors.append('Scenario fixtures:\n  ' + (result.stdout + result.stderr).strip().replace('\n', '\n  '))
    else:
        absent = [p for p in listed if not (root / p).is_file()]
        modified = [p for p in listed if (root / p).is_file() and sha256(root / p) != listed[p].get('sha256')]
        if absent:
            notes.append(f'{len(absent)} packaged files absent; record exclusions in PROJECT_PROFILE.md: ' + ', '.join(absent))
        notes.append(f'{len(modified)} packaged files modified from upstream (expected for templates and registers).')

    counts = placeholders(files, manifest)
    code_total = sum(c for c, _ in counts.values())
    release_total = sum(r for _, r in counts.values())
    if not template:
        for path, (code, release) in sorted(counts.items()):
            notes.append(f'  {path}: {code} before implementation, {release} before release')
    if args.require == 'code' and code_total:
        errors.append(f'{code_total} placeholders remain in the "Required before implementation" section of PROJECT_PROFILE.md')
    if args.require == 'release' and code_total + release_total:
        errors.append(f'{code_total + release_total} placeholders remain; fill them or record exclusions before release')

    label = 'template' if template else 'project'
    if errors:
        print('\n'.join(errors))
        print(f'FAIL ({label} mode): {len(errors)} problem(s).')
        sys.exit(1)
    print(f'PASS ({label} mode): {len(listed)} packaged files; links, adapters and shims consistent.')
    print('\n'.join(notes + [f'Placeholders: {code_total} before implementation, {release_total} before release. '
                             'No project acceptance is implied.']))


if __name__ == '__main__':
    main()
